// Normalized string helper for resilient lookups
function normalizeLocationName(name?: string): string {
  if (!name) return '';
  return name
    .replace(/^(ខេត្ត|រាជធានី|ស្រុក|ខណ្ឌ|ក្រុង|ឃុំ|សង្កាត់|ភូមិ|សាលាបឋមសិក្សា)\s*/i, '')
    .trim()
    .toLowerCase();
}

// Global cached maps
const provinceMap = new Map<string, CambodiaLocation>();
const districtMap = new Map<string, DistrictItem>(); // Key: "provNormalized:distNormalized"
const communeMap = new Map<string, CommuneItem>();   // Key: "provNorm:distNorm:commNorm"
const schoolByCodeMap = new Map<string, { school: PrimarySchoolItem; province: string; district: string; commune: string; village?: string }>();
const allSchoolsList: { school: PrimarySchoolItem; province: string; district: string; commune: string; village?: string }[] = [];

// Initialize maps once at module load
CAMBODIA_LOCATIONS.forEach(prov => {
  provinceMap.set(prov.province, prov);
  provinceMap.set(normalizeLocationName(prov.province), prov);

  prov.districts.forEach(dist => {
    const distKey = `${normalizeLocationName(prov.province)}:${normalizeLocationName(dist.name)}`;
    districtMap.set(distKey, dist);

    dist.communes.forEach(comm => {
      const commKey = `${distKey}:${normalizeLocationName(comm.name)}`;
      communeMap.set(commKey, comm);

      comm.primarySchools.forEach(sch => {
        const item = {
          school: sch,
          province: prov.province,
          district: dist.name,
          commune: comm.name,
          village: sch.village
        };
        if (sch.code) {
          schoolByCodeMap.set(sch.code.trim(), item);
        }
        allSchoolsList.push(item);
      });
    });
  });
});

