export interface LocationSearchResult {
  type: 'province' | 'district' | 'commune' | 'village' | 'school';
  name: string;
  code?: string;
  province: string;
  district?: string;
  commune?: string;
  village?: string;
  badge?: string;
}

/**
 * Fast search across Provinces, Districts, Communes, Villages, and Schools
 */
export function searchLocations(keyword: string, limit: number = 10): LocationSearchResult[] {
  if (!keyword || !keyword.trim()) return [];
  const q = keyword.trim().toLowerCase();
  const qNorm = normalizeLocationName(keyword);
  const results: LocationSearchResult[] = [];

  // Search schools first as primary target
  const schoolMatches = searchSchools(keyword, limit);
  for (const s of schoolMatches) {
    results.push({
      type: 'school',
      name: s.name,
      code: s.code,
      province: s.province,
      district: s.district,
      commune: s.commune,
      village: s.village,
      badge: s.code ? `កូដ: ${s.code}` : undefined
    });
    if (results.length >= limit) return results;
  }

  // Search provinces/districts/communes
  for (const prov of CAMBODIA_LOCATIONS) {
    if (prov.province.toLowerCase().includes(q) || normalizeLocationName(prov.province).includes(qNorm)) {
      results.push({
        type: 'province',
        name: prov.province,
        code: prov.code,
        province: prov.province
      });
      if (results.length >= limit) return results;
    }

    for (const dist of prov.districts) {
      if (dist.name.toLowerCase().includes(q) || normalizeLocationName(dist.name).includes(qNorm)) {
        results.push({
          type: 'district',
          name: dist.name,
          code: dist.code,
          province: prov.province,
          district: dist.name
        });
        if (results.length >= limit) return results;
      }

      for (const comm of dist.communes) {
        if (comm.name.toLowerCase().includes(q) || normalizeLocationName(comm.name).includes(qNorm)) {
          results.push({
            type: 'commune',
            name: comm.name,
            code: comm.code,
            province: prov.province,
            district: dist.name,
            commune: comm.name
          });
          if (results.length >= limit) return results;
        }
      }
    }
  }

  return results;
}

