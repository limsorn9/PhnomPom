/**
 * Get all 25 Provinces & Municipalities in Cambodia
 */
export function getProvinces(): string[] {
  return CAMBODIA_LOCATIONS.map(l => l.province);
}

/**
 * Get province administrative object
 */
export function getProvinceObject(provinceName: string): CambodiaLocation | undefined {
  if (!provinceName) return undefined;
  return provinceMap.get(provinceName) || provinceMap.get(normalizeLocationName(provinceName));
}

/**
 * Get Districts / Khans / Krongs by Province name (Instant lookup)
 */
export function getDistricts(provinceName: string): string[] {
  if (!provinceName) return [];
  const prov = getProvinceObject(provinceName);
  if (!prov || !Array.isArray(prov.districts)) return [];
  return prov.districts.map(d => d.name);
}

/**
 * Get District administrative object
 */
export function getDistrictObject(provinceName: string, districtName: string): DistrictItem | undefined {
  if (!provinceName || !districtName) return undefined;
  const key = `${normalizeLocationName(provinceName)}:${normalizeLocationName(districtName)}`;
  return districtMap.get(key);
}

/**
 * Get Communes / Sangkats by Province and District (Instant lookup)
 */
export function getCommunes(provinceName: string, districtName: string): string[] {
  if (!provinceName || !districtName) return [];
  const dist = getDistrictObject(provinceName, districtName);
  if (!dist || !Array.isArray(dist.communes)) return [];
  return dist.communes.map(c => c.name);
}

/**
 * Get Commune administrative object
 */
export function getCommuneObject(provinceName: string, districtName: string, communeName: string): CommuneItem | undefined {
  if (!provinceName || !districtName || !communeName) return undefined;
  const key = `${normalizeLocationName(provinceName)}:${normalizeLocationName(districtName)}:${normalizeLocationName(communeName)}`;
  return communeMap.get(key);
}

/**
 * Get Villages by Province, District, and Commune (Instant lookup)
 */
export function getVillages(provinceName: string, districtName: string, communeName: string): string[] {
  if (!provinceName || !districtName || !communeName) return [];
  const comm = getCommuneObject(provinceName, districtName, communeName);
  if (!comm || !Array.isArray(comm.villages)) return [];
  return comm.villages;
}

/**
 * Get Primary Schools list with full details (Name + Official MoEYS School Code)
 */
export function getPrimarySchoolsWithCodes(
  provinceName: string,
  districtName: string,
  communeName: string,
  villageName?: string
): PrimarySchoolItem[] {
  if (!provinceName || !districtName || !communeName) return [];
  const comm = getCommuneObject(provinceName, districtName, communeName);
  if (!comm || !Array.isArray(comm.primarySchools)) return [];

  // If a specific village is chosen and has matched schools, prioritize them, otherwise return commune schools
  if (villageName) {
    const vNorm = normalizeLocationName(villageName);
    const matchedByVillage = comm.primarySchools.filter(
      s => s.village && normalizeLocationName(s.village) === vNorm
    );
    if (matchedByVillage.length > 0) {
      return matchedByVillage;
    }
  }

  return comm.primarySchools;
}

/**
 * Get list of primary school names (Backwards-compatible API)
 */
export function getPrimarySchools(
  provinceName: string,
  districtName: string,
  communeName: string,
  villageName?: string
): string[] {
  const items = getPrimarySchoolsWithCodes(provinceName, districtName, communeName, villageName);
  return items.map(s => s.name);
}

/**
 * Get official MoEYS School Code from School Name and Location
 */
export function getSchoolCode(
  schoolName: string,
  provinceName?: string,
  districtName?: string,
  communeName?: string
): string {
  if (!schoolName) return '';

  // 1. Direct search in commune if provided
  if (provinceName && districtName && communeName) {
    const schools = getPrimarySchoolsWithCodes(provinceName, districtName, communeName);
    const targetNorm = normalizeLocationName(schoolName);
    const match = schools.find(s => normalizeLocationName(s.name) === targetNorm || s.name === schoolName);
    if (match) return match.code;
  }

  // 2. Global search in all schools list
  const sNorm = normalizeLocationName(schoolName);
  const found = allSchoolsList.find(item => normalizeLocationName(item.school.name) === sNorm);
  return found ? found.school.code : '';
}

