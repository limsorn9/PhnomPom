export function findSchoolByCode(schoolCode: string): {
  school: PrimarySchoolItem;
  province: string;
  district: string;
  commune: string;
  village?: string;
} | undefined {
  if (!schoolCode) return undefined;
  return schoolByCodeMap.get(schoolCode.trim());
}

/**
 * Find complete geographical location hierarchy from school name or code
 */
export function findLocationBySchool(schoolNameOrCode: string): {
  province: string;
  district: string;
  commune: string;
  village?: string;
  schoolName: string;
  schoolCode: string;
} | undefined {
  if (!schoolNameOrCode) return undefined;

  // Search by code first
  const byCode = schoolByCodeMap.get(schoolNameOrCode.trim());
  if (byCode) {
    return {
      province: byCode.province,
      district: byCode.district,
      commune: byCode.commune,
      village: byCode.village,
      schoolName: byCode.school.name,
      schoolCode: byCode.school.code
    };
  }

  // Search by name
  const sNorm = normalizeLocationName(schoolNameOrCode);
  const byName = allSchoolsList.find(item => normalizeLocationName(item.school.name) === sNorm || item.school.name.includes(schoolNameOrCode));
  if (byName) {
    return {
      province: byName.province,
      district: byName.district,
      commune: byName.commune,
      village: byName.village,
      schoolName: byName.school.name,
      schoolCode: byName.school.code
    };
  }

  return undefined;
}

/**
 * Search across all primary schools in Cambodia (Instant search)
 */
export function searchSchools(keyword: string, limit: number = 20): {
  province: string;
  district: string;
  commune: string;
  village?: string;
  name: string;
  code: string;
}[] {
  if (!keyword || !keyword.trim()) return [];
  const q = keyword.trim().toLowerCase();
  const qNorm = normalizeLocationName(keyword);

  const results: {
    province: string;
    district: string;
    commune: string;
    village?: string;
    name: string;
    code: string;
  }[] = [];

  for (const item of allSchoolsList) {
    const nameMatch = item.school.name.toLowerCase().includes(q) || normalizeLocationName(item.school.name).includes(qNorm);
    const codeMatch = item.school.code.toLowerCase().includes(q);
    const provMatch = item.province.toLowerCase().includes(q);
    const distMatch = item.district.toLowerCase().includes(q);

    if (nameMatch || codeMatch || (q.length >= 3 && (provMatch || distMatch))) {
      results.push({
        province: item.province,
        district: item.district,
        commune: item.commune,
        village: item.village,
        name: item.school.name,
        code: item.school.code
      });
      if (results.length >= limit) break;
    }
  }

  return results;
}

/**
 * Format a full standard Cambodian address string
 */
export function formatCambodiaAddress(addr: {
  houseNumber?: string;
  streetNumber?: string;
  village?: string;
  commune?: string;
  district?: string;
  province?: string;
}): string {
  const parts: string[] = [];
  if (addr.houseNumber) parts.push(`ផ្ទះលេខ${addr.houseNumber.replace(/^ផ្ទះលេខ\s*/, '')}`);
  if (addr.streetNumber) parts.push(`ផ្លូវ${addr.streetNumber.replace(/^ផ្លូវ\s*/, '')}`);
  if (addr.village) parts.push(addr.village.startsWith('ភូមិ') ? addr.village : `ភូមិ${addr.village}`);
  if (addr.commune) parts.push(addr.commune.startsWith('ឃុំ') || addr.commune.startsWith('សង្កាត់') ? addr.commune : `ឃុំ${addr.commune}`);
  if (addr.district) parts.push(addr.district.startsWith('ស្រុក') || addr.district.startsWith('ខណ្ឌ') || addr.district.startsWith('ក្រុង') ? addr.district : `ស្រុក${addr.district}`);
  if (addr.province) parts.push(addr.province.startsWith('ខេត្ត') || addr.province.startsWith('រាជធានី') ? addr.province : `ខេត្ត${addr.province}`);

  return parts.join(' ');
}

